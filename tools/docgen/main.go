// docgen compiles plankit's documentation source (skills/<topic>/SKILL.md)
// into the help package's intermediate representation.
//
// For each topic it writes <out>/ir/<topic>.json (the compiled IR) and
// <out>/raw/<topic>.md (the authored bytes, untouched). Anything outside
// the authoring subset is a build failure: the schema is the contract,
// and "does it compile" is the validation rule.
//
// Run from the repository root via: make docs
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/markwharton/plankit/internal/help"
	"github.com/yuin/goldmark"
	"github.com/yuin/goldmark/ast"
	"github.com/yuin/goldmark/text"
)

func main() {
	skillsDir := flag.String("skills", "", "Directory of <topic>/SKILL.md sources (required)")
	outDir := flag.String("out", "", "Output directory for ir/ and raw/ (required)")
	siteDir := flag.String("site", "", "Also build the website into this directory (optional)")
	notesAll := flag.String("notes", "released", "Which release notes the site renders: released (tag exists) or all (local preview)")
	links := flag.String("links", "clean", "Internal link form: clean (/help/ship, for Cloudflare Pages) or html (/help/ship.html, for a local static server)")
	rootDir := flag.String("root", "", "Repository root, for -site (README.md, docs/, CHANGELOG.md, site/)")
	pkBin := flag.String("pk", "", "Built pk binary; when given, the site's front page runs it in a scratch repository")
	platforms := flag.String("platforms", "", "The release platforms as os-arch names, space separated (the Makefile's TRIPLES); each gets a download redirect")
	flag.Parse()
	if *skillsDir == "" || *outDir == "" {
		fmt.Fprintln(os.Stderr, "usage: docgen -skills <dir> -out <dir> [-site <dir> -root <dir>]")
		os.Exit(2)
	}
	if changed, err := updateRegions(*skillsDir); err != nil {
		fmt.Fprintf(os.Stderr, "docgen: regions: %v\n", err)
		os.Exit(1)
	} else if len(changed) > 0 {
		fmt.Fprintf(os.Stderr, "docgen: regions rewritten: %s\n", strings.Join(changed, ", "))
	}
	if err := compileAll(*skillsDir, *outDir); err != nil {
		fmt.Fprintf(os.Stderr, "docgen: %v\n", err)
		os.Exit(1)
	}
	if *siteDir != "" {
		if *rootDir == "" {
			fmt.Fprintln(os.Stderr, "docgen: -site requires -root")
			os.Exit(2)
		}
		if *links == "html" {
			linkExt = ".html"
		}
		if err := buildSite(*rootDir, *skillsDir, *siteDir, *pkBin, *notesAll == "all", strings.Fields(*platforms)); err != nil {
			fmt.Fprintf(os.Stderr, "docgen: site: %v\n", err)
			os.Exit(1)
		}
	}
}

func compileAll(skillsDir, outDir string) error {
	entries, err := os.ReadDir(skillsDir)
	if err != nil {
		return err
	}
	for _, sub := range []string{"ir", "raw"} {
		dir := filepath.Join(outDir, sub)
		if err := os.RemoveAll(dir); err != nil {
			return err
		}
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	n := 0
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		topic := e.Name()
		src := filepath.Join(skillsDir, topic, "SKILL.md")
		raw, err := os.ReadFile(src)
		if err != nil {
			return err
		}
		if bad := scanHidden(raw); len(bad) > 0 {
			return fmt.Errorf("%s: %s", src, strings.Join(bad, "; "))
		}
		d, err := compile(topic, raw)
		if err != nil {
			return fmt.Errorf("%s: %w", src, err)
		}
		out, err := json.MarshalIndent(d, "", "  ")
		if err != nil {
			return err
		}
		out = append(out, '\n')
		if err := os.WriteFile(filepath.Join(outDir, "ir", topic+".json"), out, 0o644); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(outDir, "raw", topic+".md"), raw, 0o644); err != nil {
			return err
		}
		n++
	}
	if n == 0 {
		return fmt.Errorf("no topics found under %s", skillsDir)
	}
	marker := `# Generated by docgen. Do not edit.

Every file under ir/ and raw/ is compiled from skills/<topic>/SKILL.md
by tools/docgen (run: make docs). ir/ is the typed representation pk
help renders on a TTY; raw/ is the authored bytes served when stdout
is not a TTY. They are committed only so the standard-library-only pk
binary can embed them without goldmark at build time. Edit the skill,
never these files: CI regenerates them and fails on any difference.
See docs/architecture.md, "One source, three consumers".
`
	if err := os.WriteFile(filepath.Join(outDir, "README.md"), []byte(marker), 0o644); err != nil {
		return err
	}
	fmt.Printf("docgen: compiled %d topics\n", n)
	return nil
}

func compile(topic string, source []byte) (*help.Doc, error) {
	fm, body, err := splitFrontmatter(source)
	if err != nil {
		return nil, err
	}
	if fm["name"] != topic {
		return nil, fmt.Errorf("frontmatter name %q must equal topic directory %q", fm["name"], topic)
	}
	if fm["description"] == "" {
		return nil, fmt.Errorf("frontmatter description is required")
	}

	root := goldmark.New().Parser().Parse(text.NewReader(body))
	c := &compiler{source: body, ids: map[string]int{}}
	blocks, err := c.blocks(root)
	if err != nil {
		return nil, err
	}
	if len(blocks) == 0 || blocks[0].Type != "heading" || blocks[0].Level != 1 {
		return nil, fmt.Errorf("document must open with a level-1 heading")
	}
	d := &help.Doc{
		Schema: help.SchemaVersion,
		Meta:   help.Meta{Name: fm["name"], Description: fm["description"]},
		Blocks: blocks,
	}
	if h := plain(blocks[0].Inlines); !help.IsCommandDoc(d) && h != topic {
		return nil, fmt.Errorf("opening heading %q must be %q for a command page or %q for a document", h, "pk "+topic, topic)
	}
	return d, nil
}

// splitFrontmatter reads a skill's frontmatter and body through the
// one frontmatter reader, and refuses a key a skill does not carry.
func splitFrontmatter(source []byte) (map[string]string, []byte, error) {
	fm, body, err := help.SplitFrontmatter(source)
	if err != nil {
		return nil, nil, err
	}
	for k := range fm {
		if k != "name" && k != "description" && k != "argument-hint" {
			return nil, nil, fmt.Errorf("unknown frontmatter key %q (allowed: name, description, argument-hint)", k)
		}
	}
	return fm, body, nil
}

type compiler struct {
	source []byte
	ids    map[string]int
}

// errSkipBlock marks a block that compiles to nothing: a region
// marker comment.
var errSkipBlock = errors.New("skip")

func (c *compiler) blocks(parent ast.Node) ([]help.Block, error) {
	out := []help.Block{}
	for n := parent.FirstChild(); n != nil; n = n.NextSibling() {
		b, err := c.block(n)
		if errors.Is(err, errSkipBlock) {
			continue
		}
		if err != nil {
			return nil, err
		}
		out = append(out, b)
	}
	return out, nil
}

func (c *compiler) block(n ast.Node) (help.Block, error) {
	switch v := n.(type) {
	case *ast.Heading:
		if v.Level > 3 {
			return help.Block{}, fmt.Errorf("heading level %d: the subset allows 1..3", v.Level)
		}
		inl, err := c.spans(n, help.Span{})
		if err != nil {
			return help.Block{}, err
		}
		return help.Block{Type: "heading", Level: v.Level, ID: c.slug(plain(inl)), Inlines: inl}, nil
	case *ast.Paragraph, *ast.TextBlock:
		inl, err := c.spans(n, help.Span{})
		if err != nil {
			return help.Block{}, err
		}
		return help.Block{Type: "para", Inlines: inl}, nil
	case *ast.FencedCodeBlock:
		var sb strings.Builder
		lines := v.Lines()
		for i := 0; i < lines.Len(); i++ {
			seg := lines.At(i)
			sb.Write(seg.Value(c.source))
		}
		return help.Block{Type: "codeblock", Lang: string(v.Language(c.source)), Text: sb.String()}, nil
	case *ast.CodeBlock:
		return help.Block{}, fmt.Errorf("indented code block: use a fenced block")
	case *ast.List:
		items := [][]help.Block{}
		for li := n.FirstChild(); li != nil; li = li.NextSibling() {
			item, err := c.blocks(li)
			if err != nil {
				return help.Block{}, err
			}
			items = append(items, item)
		}
		return help.Block{Type: "list", Ordered: v.IsOrdered(), Items: items}, nil
	case *ast.Blockquote:
		inner, err := c.blocks(n)
		if err != nil {
			return help.Block{}, err
		}
		return help.Block{Type: "quote", Blocks: inner}, nil
	case *ast.ThematicBreak:
		return help.Block{Type: "rule"}, nil
	case *ast.HTMLBlock:
		// Only region markers, which are comments; nothing else renders.
		var raw bytes.Buffer
		for i := 0; i < v.Lines().Len(); i++ {
			seg := v.Lines().At(i)
			raw.Write(seg.Value(c.source))
		}
		if text := strings.TrimSpace(raw.String()); strings.HasPrefix(text, "<!--") && strings.HasSuffix(text, "-->") {
			return help.Block{}, errSkipBlock
		}
		return help.Block{}, fmt.Errorf("HTML block: outside the subset")
	default:
		return help.Block{}, fmt.Errorf("unsupported block %s: outside the subset", n.Kind())
	}
}

// spans flattens the inline tree onto flag-carrying spans: nesting
// resolves at compile time so the runtime walker is a single loop.
func (c *compiler) spans(parent ast.Node, state help.Span) ([]help.Span, error) {
	out := []help.Span{}
	for n := parent.FirstChild(); n != nil; n = n.NextSibling() {
		switch v := n.(type) {
		case *ast.Text:
			t := string(v.Segment.Value(c.source))
			if v.SoftLineBreak() {
				t += " " // soft breaks collapse: the runtime re-wraps
			}
			out = appendText(out, state, t)
			if v.HardLineBreak() {
				out = append(out, help.Span{Type: "br"})
			}
		case *ast.String:
			out = appendText(out, state, string(v.Value))
		case *ast.Emphasis:
			sub := state
			if v.Level >= 2 {
				sub.Strong = true
			} else {
				sub.Em = true
			}
			inner, err := c.spans(n, sub)
			if err != nil {
				return nil, err
			}
			out = append(out, inner...)
		case *ast.CodeSpan:
			// A code span may cross a source line; CommonMark treats the
			// line ending as a space, and so does the terminal.
			out = append(out, help.Span{Type: "code", Text: strings.ReplaceAll(nodeText(n, c.source), "\n", " "), URL: state.URL})
		case *ast.Link:
			sub := state
			sub.URL = string(v.Destination)
			inner, err := c.spans(n, sub)
			if err != nil {
				return nil, err
			}
			out = append(out, inner...)
		case *ast.AutoLink:
			u := string(v.URL(c.source))
			out = append(out, help.Span{Type: "text", Text: u, Strong: state.Strong, Em: state.Em, URL: u})
		case *ast.RawHTML:
			return nil, fmt.Errorf("inline HTML: outside the subset")
		case *ast.Image:
			return nil, fmt.Errorf("image: outside the subset")
		default:
			return nil, fmt.Errorf("unsupported inline %s: outside the subset", n.Kind())
		}
	}
	return out, nil
}

// appendText merges consecutive same-styled text into one span.
func appendText(out []help.Span, state help.Span, t string) []help.Span {
	if t == "" {
		return out
	}
	if n := len(out); n > 0 {
		last := &out[n-1]
		if last.Type == "text" && last.Strong == state.Strong && last.Em == state.Em && last.URL == state.URL {
			last.Text += t
			return out
		}
	}
	return append(out, help.Span{Type: "text", Text: t, Strong: state.Strong, Em: state.Em, URL: state.URL})
}

func nodeText(n ast.Node, source []byte) string {
	var sb bytes.Buffer
	for c := n.FirstChild(); c != nil; c = c.NextSibling() {
		switch v := c.(type) {
		case *ast.Text:
			sb.Write(v.Segment.Value(source))
		case *ast.String:
			sb.Write(v.Value)
		}
	}
	return sb.String()
}

func plain(spans []help.Span) string {
	var sb strings.Builder
	for _, s := range spans {
		sb.WriteString(s.Text)
	}
	return sb.String()
}

var slugStrip = regexp.MustCompile(`[^a-z0-9]+`)

// slug produces GitHub-style heading ids, deduplicated per document.
func (c *compiler) slug(title string) string {
	s := strings.Trim(slugStrip.ReplaceAllString(strings.ToLower(title), "-"), "-")
	if s == "" {
		s = "section"
	}
	c.ids[s]++
	if n := c.ids[s]; n > 1 {
		return fmt.Sprintf("%s-%d", s, n)
	}
	return s
}

// hiddenRunes are invisible or direction-altering code points that have
// no place in an English skill file. Skills ship verbatim into other
// people's model contexts, so anything a reader cannot see is rejected
// at build time: C0 controls (except \n and \t) and DEL cover ANSI
// escapes and raw control bytes; the rest are the Trojan Source set of
// bidirectional controls plus the zero-width and invisible joiners.
var hiddenRunes = map[rune]string{
	0x00AD: "soft hyphen",
	0x034F: "combining grapheme joiner",
	0x061C: "arabic letter mark",
	0x200B: "zero width space",
	0x200C: "zero width non-joiner",
	0x200D: "zero width joiner",
	0x200E: "left-to-right mark",
	0x200F: "right-to-left mark",
	0x202A: "left-to-right embedding",
	0x202B: "right-to-left embedding",
	0x202C: "pop directional formatting",
	0x202D: "left-to-right override",
	0x202E: "right-to-left override",
	0x2060: "word joiner",
	0x2066: "left-to-right isolate",
	0x2067: "right-to-left isolate",
	0x2068: "first strong isolate",
	0x2069: "pop directional isolate",
	0xFEFF: "zero width no-break space (BOM)",
}

// scanHidden reports every hidden or control character in the file,
// one finding per line/rune, so a poisoned skill cannot compile.
func scanHidden(raw []byte) []string {
	var bad []string
	line := 1
	for _, r := range string(raw) {
		if r == '\n' {
			line++
			continue
		}
		if r == '\t' {
			continue
		}
		if r < 0x20 || r == 0x7F {
			bad = append(bad, fmt.Sprintf("line %d: control character U+%04X", line, r))
			continue
		}
		if name, ok := hiddenRunes[r]; ok {
			bad = append(bad, fmt.Sprintf("line %d: hidden character U+%04X (%s)", line, r, name))
		}
	}
	return bad
}
